/** Une police : hauteur des signes, espace entre deux signes, et les signes eux-mêmes. */
export interface DmdFont {
  height: number;
  spacing: number;
  glyphs: Map<string, DotBitmap>;
}

function fromRows(rows: string[]): DotBitmap {
  const w = rows[0]!.length;
  const h = rows.length;
  const px = new Uint8Array(w * h);
  rows.forEach((row, y) => [...row].forEach((c, x) => (px[y * w + x] = c === '#' ? 1 : 0)));
  return { w, h, px };
}

function fontOf(height: number, spacing: number, rows: Record<string, string[]>): DmdFont {
  return { height, spacing, glyphs: new Map(Object.entries(rows).map(([k, r]) => [k, fromRows(r)])) };
}

/** Chaque point devient un carré de 2 × 2 : les coins chanfreinés de la police restent nets. */
export function doubled(src: DotBitmap): DotBitmap {
  const out = new Uint8Array(src.w * 2 * src.h * 2);
  for (let y = 0; y < src.h * 2; y++) for (let x = 0; x < src.w * 2; x++) out[y * src.w * 2 + x] = src.px[(y >> 1) * src.w + (x >> 1)]!;
  return { w: src.w * 2, h: src.h * 2, px: out };
}

